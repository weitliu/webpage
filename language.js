(() => {
  const button = document.querySelector('.language-toggle');
  let language = navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
  try {
    const saved = localStorage.getItem('axis-language');
    if (saved === 'en' || saved === 'zh-CN') language = saved;
  } catch (_) { /* The switch also works when storage is unavailable. */ }
  function render() {
    const chinese = language === 'zh-CN';
    document.documentElement.lang = language;
    document.querySelectorAll('[data-i18n]').forEach(element => {
      element.textContent = axisTranslations[element.dataset.i18n][language];
    });
    document.title = chinese ? 'AXIS AI — 让智能融入日常经营' : 'AXIS AI — Intelligence for everyday industry';
    document.querySelector('meta[name="description"]').content = chinese
      ? 'AXIS AI 为零售、批发、仓储和运输行业打造人工智能解决方案，帮助超市减少录单投入，看清库存、利润与经营状况。'
      : 'AXIS AI builds AI solutions for retail, wholesale, warehousing, and transportation, helping supermarkets reduce invoice entry and understand inventory, profit, and business performance.';
    document.querySelector('.brand[aria-label]').setAttribute('aria-label', chinese ? 'AXIS AI 首页' : 'AXIS AI home');
    document.querySelector('.page-tabs').setAttribute('aria-label', chinese ? '网站栏目' : 'Website sections');
    document.querySelector('video').setAttribute('aria-label', chinese ? 'AXIS AI 介绍视频' : 'AXIS AI introduction video');
    button.textContent = chinese ? 'English' : '中文';
    button.lang = chinese ? 'en' : 'zh-CN';
    button.setAttribute('aria-label', chinese ? 'Switch to English' : '切换到中文');
    button.hidden = false;
  }
  button.addEventListener('click', () => {
    language = language === 'en' ? 'zh-CN' : 'en';
    render();
    try { localStorage.setItem('axis-language', language); } catch (_) {}
  });
  render();
})();
